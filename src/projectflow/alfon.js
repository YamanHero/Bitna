export const ALFON_STAGE_IDS = GROUPS.map((g) => g.id);

export function makeAlfonProject() {
  const now = new Date().toISOString();
  return {
    id: uid(),
    name: ALFON_NAME,
    type: 'it',
    owner: '',
    budget: '',
    targetDate: '',
    createdAt: now,
    status: 'prep',
    statusLog: [{ status: 'prep', at: now }],
    stages: GROUPS.map(({ id, title }) => ({ id, title })),
    tasks: GROUPS.flatMap((g) => g.tasks.map((title) => ({ id: uid(), stage: g.id, title, done: false }))),
    stageMeta: {},
    agent: { profile: 'elections-pm-360', createdBy: 'agent-setup', at: now },
  };
}

